#!/usr/bin/env python3
"""Generate the JNI glue for libUnrealEngine3.so (Dark Meadow: The Pact) from jni_tables.json.

  python3 tools/gen_java.py            (run from the project root)

Writes (do not edit by hand, re-run this script instead):
  source/java_callbacks.h   prototypes of every native->Java callback ("jcb_<name>")
  source/java_tables.c      FalsoJNI method/field tables + weak default stubs for every callback
  source/engine_natives.h   typed function pointers for the Java->native entry points ("ue3_<name>")
  source/engine_natives.c   the pointer definitions and the table used to bind them by name

Real behaviour for a callback is provided by defining jcb_<name> (strong) in source/java_impl.c;
it overrides the weak stub generated here.
"""
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
T = json.load(open(os.path.join(ROOT, 'tools', 'jni_tables.json')))
SRC = os.path.join(ROOT, 'source')
HDR = '/* GENERATED by tools/gen_java.py from tools/jni_tables.json - do not edit. */\n'

# ---- JNI signature helpers -------------------------------------------------------------------
def parse_sig(sig):
    m = re.match(r'\((.*)\)(.+)$', sig)
    args, ret = m.group(1), m.group(2)
    out, i = [], 0
    while i < len(args):
        c = args[i]
        if c == 'L':
            j = args.index(';', i)
            out.append(args[i:j + 1]); i = j + 1
        elif c == '[':
            j = i
            while args[j] == '[': j += 1
            if args[j] == 'L': j = args.index(';', j)
            out.append(args[i:j + 1]); i = j + 1
        else:
            out.append(c); i += 1
    return out, ret

CT = {'Z': 'jboolean', 'B': 'jbyte', 'C': 'jchar', 'S': 'jshort', 'I': 'jint',
      'J': 'jlong', 'F': 'jfloat', 'D': 'jdouble', 'V': 'void'}
def ctype(t):
    if t in CT: return CT[t]
    if t == 'Ljava/lang/String;': return 'jstring'
    if t.startswith('['): return 'jobjectArray'
    return 'jobject'

MT = {'V': 'VOID', 'Z': 'BOOLEAN', 'B': 'BYTE', 'C': 'CHAR', 'S': 'SHORT', 'I': 'INT',
      'J': 'LONG', 'F': 'FLOAT', 'D': 'DOUBLE'}
def mtype(ret): return MT.get(ret, 'OBJECT')
TABLE = {'VOID': 'MethodsVoid methodsVoid', 'BOOLEAN': 'MethodsBoolean methodsBoolean',
         'BYTE': 'MethodsByte methodsByte', 'CHAR': 'MethodsChar methodsChar',
         'SHORT': 'MethodsShort methodsShort', 'INT': 'MethodsInt methodsInt',
         'LONG': 'MethodsLong methodsLong', 'FLOAT': 'MethodsFloat methodsFloat',
         'DOUBLE': 'MethodsDouble methodsDouble', 'OBJECT': 'MethodsObject methodsObject'}
DEFAULT = {'void': '', 'jboolean': 'JNI_FALSE', 'jbyte': '0', 'jchar': '0', 'jshort': '0', 'jint': '0',
           'jlong': '0', 'jfloat': '0.0f', 'jdouble': '0.0', 'jstring': 'NULL', 'jobject': 'NULL',
           'jobjectArray': 'NULL'}

# ---- unique callbacks (the engine lists JavaCallback_SetFixedSizeScale twice) ----------------
cbs, seen = [], set()
for c in T['callbacks'] + T.get('extra_callbacks', []):
    if c['name'] in seen: continue
    seen.add(c['name']); cbs.append(c)

EGL_CLS = T['class'] + '$EGLConfigParms'
INIT_NAME = EGL_CLS + '/<init>'          # FalsoJNI's GetMethodID builds "<class>/<init>" for constructors
EGL_INT_FIELDS = ['redSize', 'greenSize', 'blueSize', 'alphaSize', 'depthSize', 'stencilSize', 'sampleBuffers']
EGL_BOOL_FIELDS = ['validConfig']

# ---- java_callbacks.h -----------------------------------------------------------------------
h = [HDR, '#ifndef DM_JAVA_CALLBACKS_H\n#define DM_JAVA_CALLBACKS_H\n\n#include <stdarg.h>\n#include <falso_jni/FalsoJNI.h>\n\n']
h.append('/* Implement any of these in source/java_impl.c; unimplemented ones fall back to a logging stub. */\n')
for c in cbs:
    _, ret = parse_sig(c['sig'])
    h.append(f"{ctype(ret)} jcb_{c['name']}(jmethodID id, va_list args);\n")
h.append(f"jobject jcb_EGLConfigParms_init(jmethodID id, va_list args);   /* {INIT_NAME} */\n")
h.append('\n#endif\n')
open(os.path.join(SRC, 'java_callbacks.h'), 'w').write(''.join(h))

# ---- java_tables.c --------------------------------------------------------------------------
c_ = [HDR, '#include <stdarg.h>\n#include <falso_jni/FalsoJNI.h>\n#include <falso_jni/FalsoJNI_Impl.h>\n'
      '#include <falso_jni/FalsoJNI_Logger.h>\n#include "java_callbacks.h"\n#include "utils/logger.h"\n\n']
c_.append('/* ---- weak default stubs: log and return a neutral value ---- */\n')
for c in cbs:
    _, ret = parse_sig(c['sig'])
    ct = ctype(ret)
    body = ('    static int logged;\n'
            f'    if (!logged) {{ logged = 1; l_warn("[JAVA] {c["name"]}: not implemented, ignored (logged once)"); }}\n')
    if ct != 'void': body += f'    return {DEFAULT[ct]};\n'
    c_.append(f"__attribute__((weak)) {ct} jcb_{c['name']}(jmethodID id, va_list args) {{\n{body}}}\n")
c_.append('\n')

# IDs start at 1: FalsoJNI returns the ID itself as the jmethodID/jfieldID, and 0 would read as NULL ("not found").
ids = {c['name']: i + 1 for i, c in enumerate(cbs)}
init_id = len(cbs) + 1

c_.append('NameToMethodID nameToMethodId[] = {\n')
for c in cbs:
    _, ret = parse_sig(c['sig'])
    c_.append(f'    {{ {ids[c["name"]]}, "{c["name"]}", METHOD_TYPE_{mtype(ret)} }},\n')
c_.append(f'    {{ {init_id}, "{INIT_NAME}", METHOD_TYPE_OBJECT }},\n')
c_.append('};\n\n')

buckets = {k: [] for k in TABLE}
for c in cbs:
    _, ret = parse_sig(c['sig'])
    buckets[mtype(ret)].append((ids[c['name']], f"jcb_{c['name']}"))
buckets['OBJECT'].append((init_id, 'jcb_EGLConfigParms_init'))
for k, decl in TABLE.items():
    ents = ''.join(f'    {{ {i}, {fn} }},\n' for i, fn in buckets[k])
    c_.append(f'{decl}[] = {{\n{ents}}};\n')
c_.append('\n')

# Static int constants the engine reads from Android classes with GetStaticFieldID/GetStaticIntField during
# startup (android.view.MotionEvent.ACTION_*, android.view.KeyEvent.KEYCODE_*). Without them every constant reads
# as 0, so the engine took a touch-up (1) for a move and never saw a finger lift.
ANDROID_INT_CONSTANTS = {
    'ACTION_DOWN': 0, 'ACTION_UP': 1, 'ACTION_MOVE': 2, 'ACTION_CANCEL': 3, 'ACTION_OUTSIDE': 4,
    'ACTION_POINTER_DOWN': 5, 'ACTION_POINTER_UP': 6, 'ACTION_MASK': 0xff,
    'ACTION_POINTER_INDEX_MASK': 0xff00, 'ACTION_POINTER_INDEX_SHIFT': 8,
    'KEYCODE_HOME': 3, 'KEYCODE_BACK': 4, 'KEYCODE_STAR': 17, 'KEYCODE_POUND': 18,
    'KEYCODE_DPAD_UP': 19, 'KEYCODE_DPAD_DOWN': 20, 'KEYCODE_DPAD_LEFT': 21, 'KEYCODE_DPAD_RIGHT': 22,
    'KEYCODE_DPAD_CENTER': 23, 'KEYCODE_COMMA': 55, 'KEYCODE_PERIOD': 56, 'KEYCODE_ALT_LEFT': 57,
    'KEYCODE_ALT_RIGHT': 58, 'KEYCODE_SHIFT_LEFT': 59, 'KEYCODE_SHIFT_RIGHT': 60, 'KEYCODE_TAB': 61,
    'KEYCODE_SPACE': 62, 'KEYCODE_ENTER': 66, 'KEYCODE_DEL': 67, 'KEYCODE_GRAVE': 68, 'KEYCODE_MINUS': 69,
    'KEYCODE_EQUALS': 70, 'KEYCODE_LEFT_BRACKET': 71, 'KEYCODE_RIGHT_BRACKET': 72, 'KEYCODE_BACKSLASH': 73,
    'KEYCODE_SEMICOLON': 74, 'KEYCODE_APOSTROPHE': 75, 'KEYCODE_SLASH': 76, 'KEYCODE_AT': 77,
    'KEYCODE_NUM': 78, 'KEYCODE_PLUS': 81, 'KEYCODE_MENU': 82,
}
ANDROID_INT_CONSTANTS.update({f'KEYCODE_{d}': 7 + d for d in range(10)})
ANDROID_INT_CONSTANTS.update({f'KEYCODE_{chr(65 + i)}': 29 + i for i in range(26)})

# EGLConfigParms fields (the engine fills them in with Set<Type>Field before calling initEGL), then the constants
fid = {}
c_.append('NameToFieldID nameToFieldId[] = {\n')
for n, name in enumerate(EGL_INT_FIELDS):   n += 1; fid[name] = n; c_.append(f'    {{ {n}, "{name}", FIELD_TYPE_INT }},\n')
for name in EGL_BOOL_FIELDS:                fid[name] = len(fid) + 1; c_.append(f'    {{ {fid[name]}, "{name}", FIELD_TYPE_BOOLEAN }},\n')
for name in ANDROID_INT_CONSTANTS:          fid[name] = len(fid) + 1; c_.append(f'    {{ {fid[name]}, "{name}", FIELD_TYPE_INT }},\n')
c_.append('};\n\n')
c_.append('FieldsInt fieldsInt[] = {\n' + ''.join(f'    {{ {fid[n]}, 0 }},\n' for n in EGL_INT_FIELDS)
          + ''.join(f'    {{ {fid[n]}, {v} }},   /* {n} */\n' for n, v in ANDROID_INT_CONSTANTS.items()) + '};\n')
c_.append('FieldsBoolean fieldsBoolean[] = {\n' + ''.join(f'    {{ {fid[n]}, JNI_TRUE }},\n' for n in EGL_BOOL_FIELDS) + '};\n')
for t in ('Byte', 'Char', 'Short', 'Long', 'Float', 'Double', 'Object'):
    c_.append(f'Fields{t} fields{t}[] = {{}};\n')
c_.append('\n__FALSOJNI_IMPL_CONTAINER_SIZES\n')
open(os.path.join(SRC, 'java_tables.c'), 'w').write(''.join(c_))

# ---- engine_natives.h / .c ------------------------------------------------------------------
def short(n): return n.replace('NativeCallback_', '')
nh = [HDR, '#ifndef DM_ENGINE_NATIVES_H\n#define DM_ENGINE_NATIVES_H\n\n#include <falso_jni/FalsoJNI.h>\n\n'
      '/* Entry points the Java activity would call, captured from RegisterNatives in JNI_OnLoad.\n'
      '   Each is NULL until engine_bind_natives() has run. */\n']
nc = [HDR, '#include <string.h>\n#include "engine_natives.h"\n#include "utils/logger.h"\n\n']
bind = []
for n in T['natives']:
    args, ret = parse_sig(n['sig'])
    plist = ', '.join(['JNIEnv *env', 'jobject thiz'] + [f'{ctype(a)} a{i}' for i, a in enumerate(args)])
    decl = f"{ctype(ret)} (*ue3_{short(n['name'])})({plist})"
    nh.append(f"extern {decl};   /* {n['name']} {n['sig']} */\n")
    nc.append(f"{decl};\n")
    bind.append(f'    {{ "{n["name"]}", (void **)&ue3_{short(n["name"])} }},\n')
nh.append('\nvoid engine_bind_natives(void);   /* look every entry point up in the captured table */\n\n#endif\n')
nc.append('\nextern int engine_find_native(const char *name, void **out);   /* engine.c */\n\n')
nc.append('static const struct { const char *name; void **slot; } bindings[] = {\n' + ''.join(bind) + '};\n\n')
nc.append('void engine_bind_natives(void) {\n    int missing = 0;\n'
          '    for (unsigned i = 0; i < sizeof(bindings) / sizeof(bindings[0]); i++) {\n'
          '        if (!engine_find_native(bindings[i].name, bindings[i].slot)) {\n'
          '            l_warn("Native \\"%s\\" was not registered by the engine.", bindings[i].name);\n'
          '            missing++;\n        }\n    }\n'
          '    l_info("Bound %d/%d engine natives.", (int)(sizeof(bindings) / sizeof(bindings[0])) - missing,\n'
          '           (int)(sizeof(bindings) / sizeof(bindings[0])));\n}\n')
open(os.path.join(SRC, 'engine_natives.h'), 'w').write(''.join(nh))
open(os.path.join(SRC, 'engine_natives.c'), 'w').write(''.join(nc))

print(f"callbacks: {len(cbs)} unique ({len(T['callbacks'])} listed) + EGLConfigParms ctor; natives: {len(T['natives'])}")
